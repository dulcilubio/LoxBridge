            workoutUUID:     uuid1.uuidString,
            status:          "On Livelox",
            distanceKm:      7.403,
            durationSeconds: 3617,
            activityTypeName: "Orienteering",
            locationName:    "Huddinge",
            createdAt:       iso("2026-10-10T14:00:00Z")?.timeIntervalSince1970,
            points:          samplePoints,
            speeds:          sampleSpeeds
        )
        guard let data = try? JSONEncoder().encode([payload]) else { return }
        UserDefaults.standard.set(data, forKey: "watchRoutePayloads")
    }

